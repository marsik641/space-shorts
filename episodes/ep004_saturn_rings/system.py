def sun_s(elev=SUN_ELEV, az=SUN_AZ):
    e, a = math.radians(elev), math.radians(az)
    return Vector((math.cos(e) * math.cos(a), math.cos(e) * math.sin(a), math.sin(e)))


SUN_S = sun_s()


def v_orbit(r_km):
    """Круговая скорость частицы на радиусе r, км/с."""
    return math.sqrt(GM / r_km)


def period_h(r_km):
    return 2 * math.pi * r_km / v_orbit(r_km) / 3600.0


def sph_s(dist, az_deg, el_deg):
    """Точка в системе S: азимут от направления на Солнце (SUN_AZ), возвышение над плоскостью колец."""
    az, el = math.radians(az_deg + SUN_AZ), math.radians(el_deg)
    return Vector((dist * math.cos(el) * math.cos(az), dist * math.cos(el) * math.sin(az), dist * math.sin(el)))


def sys_rot(view_s, roll_deg):
    """Поворот S → мир (Matrix 3×3) под камеру spacekit (Track To, «вверх» — мировая Z): при взгляде view_s (в S,
    от камеры к цели) плоскость колец в кадре повёрнута на roll_deg против часовой стрелки. Камера в S «держит»
    вверх up' = up·cos ρ + right·sin ρ; поворот переводит up' в мировую Z (взгляд остаётся горизонтальным)."""
    d = Vector(view_s).normalized()
    z = Vector((0, 0, 1))
    right = d.cross(z).normalized()
    up = right.cross(d).normalized()
    r = math.radians(roll_deg)
    up_r = (up * math.cos(r) + right * math.sin(r)).normalized()
    return up_r.rotation_difference(z).to_matrix()
